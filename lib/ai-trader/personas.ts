// 実装済み人格IDの一覧（PERSONASレジストリから動的導出）。
// APIの受理境界（app/api/ai-session/route.ts）はこれを正とする。ハードコード配列を別途持つと
// 「未実装なのに受理されGENERICへ無言フォールバックする」乖離が起きる（COMPANY.md 原則9のレビュー指摘）。
// PERSONASに新しい人格エントリを追加するだけで、APIも自動的に解禁される。
export const IMPLEMENTED_PERSONA_IDS = Object.keys(PERSONAS) as InvestorId[]

// session.persona からプロンプト用テキストを取得する。未定義・未実装の人格は既定（汎用）にフォールバックする。
export function getPersonaText(id?: InvestorId): PersonaText {
  if (!id) return GENERIC
  return PERSONAS[id] ?? GENERIC
}
