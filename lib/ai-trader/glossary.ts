//
// オーナーの指摘: 「文章がそこに収めようととても難しい文章になっている。初心者でも分かるように」。
// AIの文は入力ログなので書き換えない（原則9）。代わりに、文中の用語に意味を添える。
// これなら過去の判断すべてに即座に効き、AIへの指示もトークンも増えない。
//
// 用語の見つけ方は2通り:
// - 札（reading-highlight.ts が数値つきで囲んだ語: `PER17.4x` `RSI54` `BB内`）→ termKeyOf
// - 札にならない地の文の語（`PER計算不能` の PER、`高レバレッジ`、`反発` など）→ termsInReading が走査
//   どちらも「この文に出てきた用語」の折りたたみに、出てきた順で並べる。
//   地の文の語の候補は、本番の判断文842本で説明の無い語を数えて多い順に選んだ（2026-09-11）。
//
// 書き方の決まり（金融商品取引法の投資助言業を避ける設計・DECISIONS.md 2026-08-23 の不変条件）:
// - 「おすすめ」「買い時」「買うべき」「割安だから」のような、売買を促す言い方をしない
// - 「高い＝良い」「安ければ上がる」と断定しない。「〜と読まれることが多い」「〜とは限らない」と幅を残す
// - 説明に別の専門用語を使うときは、その場で言い換える
// scripts/check-glossary.ts が字数と禁止語を検査する。

