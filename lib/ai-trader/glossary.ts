export type TermKey = keyof typeof GLOSSARY

// 長い見出し語から先に照合する（「配当利回り」を「配当」より先に、「MACD強気」を「MACD」より先に）。
const KEYS = (Object.keys(GLOSSARY) as TermKey[]).sort((a, b) => b.length - a.length)

/** reading-highlight.ts が札にした文字列（例: `PER17.4x` `RSI54` `BB内`）から用語を引く。無ければ null。 */
export function termKeyOf(chipText: string): TermKey | null {
  const t = chipText.trim()
  if (/^RSI/.test(t)) return 'RSI'
  for (const k of KEYS) if (t.startsWith(k)) return k
  return null
}

const LATIN = /^[A-Za-z/]+$/
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
const PATTERNS = new Map<TermKey, RegExp>(
  KEYS.map((k) => {
    const m = (GLOSSARY[k] as Term).match
    if (m) return [k, new RegExp(m.source, 'g')]
    // 英字の略語は前後が英字でないときだけ（`SUPER 8` の PER に当てない）
    return [k, LATIN.test(k) ? new RegExp(`(?<![A-Za-z])${escape(k)}(?![A-Za-z])`, 'g') : new RegExp(escape(k), 'g')]
  }),
)

/**
 * reading-highlight の分割結果から、文に出てきた用語を「出てきた順・重複なし」で返す。
 * 札はその札の語、地の文は見出し語を長い順に走査する（重なる短い語は数えない: 「配当利回り」の中の「配当」など）。
 * 文そのものは変えない（表示の分割にも使わない）。
 */
export function termsInReading(segments: ReadonlyArray<{ text: string; kind: string }>): TermKey[] {
  const hits: Array<{ pos: number; key: TermKey }> = []
  let offset = 0
  for (const s of segments) {
    if (s.kind !== 'plain') {
      const k = termKeyOf(s.text)
      if (k) hits.push({ pos: offset, key: k })
    } else {
      const taken: Array<[number, number]> = []
      for (const k of KEYS) {
        const re = PATTERNS.get(k)!
        re.lastIndex = 0
        let m: RegExpExecArray | null
        while ((m = re.exec(s.text))) {
          if (m[0].length === 0) { re.lastIndex++; continue }
          const a = m.index, z = a + m[0].length
          if (taken.some(([x, y]) => a < y && x < z)) continue
          taken.push([a, z])
          hits.push({ pos: offset + a, key: k })
        }
      }
    }
    offset += s.text.length
  }
  hits.sort((p, q) => p.pos - q.pos)
  const out: TermKey[] = []
  for (const h of hits) if (!out.includes(h.key)) out.push(h.key)
  return out
}
