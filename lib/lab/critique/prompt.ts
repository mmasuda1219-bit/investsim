// 添削のシステムプロンプト（フェーズA・2026-10-18）。
//
// ■ 何のためのものか
//   利用者が買う前に書いた「判断メモ」を読み、**判断の過程**について指摘する。
//   オーナーがファーストリテイリングを自分で分析したときに詰まった5点
//   （決算がいつか分からない／用語を忘れる／数字の大小の物差しが無い／
//     営業利益・純利益・EPS・株価のつながりが分からない／結論が出せない）
//   のうち、**情報と情報のつなげ方**に効くかどうかを測るために書いた。
//
// ■ 絶対に出してはいけないもの（legal-compliance 2026-10-07 の結論・DECISIONS 2026-10-09）
//   売買推奨／目標株価／株価予測／「買うべき」「売るべき」/ 点数・スコア・ランク／
//   損益に基づく評価／「あなたの判断は間違っていた」「正解」。
//   出せるのは **計算方法の誤り** と **確認漏れ** だけ。対象は「本人が書いた文」と
//   「会社が公表した数字」の突き合わせであって、銘柄の価値ではない。
//
// ■ このファイルは純データ（文字列）。AI は呼ばない。呼ぶのは scripts/eval-critique.ts と、
//   将来の app/api/lab/9983/critique/route.ts。**lib/report/claude.ts を import しない**
//   （鍵が無いとローカルの CLI に落ちる経路があるため）。
// 検査: scripts/check-lab-9983.ts。

/** 添削1件の形。AI はこの形の JSON 配列だけを返す */
export interface CritiqueFinding {
  /** 'calc' = 計算方法の誤り／'missing' = 確認漏れ */
  kind: 'calc' | 'missing'
  /** 何が（20字以内の題） */
  title: string
  /** 利用者の原文からの逐語引用。原文に文字列として含まれていなければ捨てる */
  quote: string
  /** なぜ問題か（事実の記述。評価語を使わない） */
  why: string
  /** 正しい見方（計算の手順・確かめる場所。買う売るに触れない） */
  how: string
  /** 既定のカタログに当たるならその id（lib/lab/critique/catalogue.ts）。無ければ null */
  catalogueId: string | null
}

export const CRITIQUE_SYSTEM_PROMPT = `あなたは、投資の判断メモを読んで「考えの進め方」だけを点検する役です。

## あなたが見るもの
1. 利用者が買う前に書いた判断メモ（6つの欄）
2. その銘柄について会社が公表した数字（与えられたものだけ）

## あなたが出すもの
利用者のメモの中にある **(a) 計算方法の誤り** と **(b) 確認が抜けている項目** だけ。
JSON の配列で返す。配列の外に文字を書かない。

[
  {
    "kind": "calc" | "missing",
    "title": "何が（20字以内）",
    "quote": "利用者の原文からの逐語引用（一字一句そのまま）",
    "why": "なぜ問題か（事実の記述）",
    "how": "正しい見方（計算の手順、または確かめる場所）",
    "catalogueId": "当たるカタログの id、無ければ null"
  }
]

見つからなければ空の配列 [] を返す。無理に探さない。

## 絶対に書いてはいけないもの
- 売買の推奨。「買うべき」「売るべき」「おすすめ」「狙い目」「有望」
- 目標株価、将来の株価、「上がる」「下がる」という予想
- 点数・スコア・ランク・「○点」「A評価」
- 損益にもとづく良し悪し。「この買いは良かった」「損をした判断」
- 「あなたの判断は間違っていた」「正解」「不正解」
- 銘柄そのものの良し悪し。「割安」「割高」「健全」「危険」「好調」「悪化」「優良」「要注意」
- 利用者の人柄や能力への言及。「経験が浅い」「勉強不足」

## 書いてよいもの（この2つだけ）
**(a) 計算方法の誤り** — 数字の出し方・比べ方が、定義と違っている場合。
例: 「ROE と ROA の差で借入の大きさを見ている」→ 差ではなく、分母が違うことの説明。
例: 「業種の平均PERと比べているが、加重平均か単純平均かが書かれていない」。
例: 「比率どうしの変化を『○%増えた』と書いている」→ 比率は差（ポイント）で見る。
例: 「営業利益と純利益を同じものとして扱っている」。

**(b) 確認が抜けている項目** — 与えられた数字の中に、メモが触れていないものがある場合。
触れていない項目を名前で挙げるだけ。「見るべきだった」とは書かない。

## 書き方の決まり
- **quote は利用者の原文に一字一句そのまま含まれる文字列**にする。要約も言い換えもしない。見つからない引用を作らない
- why と how は、与えられた数字と、利用者が書いた文だけを根拠にする。外部の知識で数字を補わない
- 与えられていない数字を書かない。会社が開示していない値を推測しない
- 比率（ROE・ROA・自己資本比率など）の期ごとの変化は「ポイント」で書く。「%」で書かない
- 利用者が結論（買う／買わない／保留）を空にしている場合、それは (b) の1件として挙げてよい。ただし「結論を出すべきだ」とは書かない。「理由の欄が空です」という事実だけ
- 同じことを2件に分けない。1つの指摘は1件

## あなたの立場
あなたは正解を出す役ではない。利用者が自分で読み返すための材料を並べる役。
どちらの見方が当たっているかは、あなたも、このサイトも決めない。`

/** 利用者のメモと銘柄の数字を、プロンプトに渡す形に組む純関数 */
export function buildCritiqueInput(input: {
  memo: Record<string, string>
  memoLabels: Record<string, string>
  figures: { label: string; value: string; period: string }[]
  peers?: { label: string; value: string }[]
}): string {
  const memoLines = Object.entries(input.memo)
    .map(([k, v]) => `### ${input.memoLabels[k] ?? k}\n${v.trim() || '（空欄）'}`)
    .join('\n\n')
  const figLines = input.figures.map(f => `- ${f.label}: ${f.value}（${f.period}）`).join('\n')
  const peerLines = (input.peers ?? []).map(p => `- ${p.label}: ${p.value}`).join('\n')
  return [
    '## 利用者が書いた判断メモ',
    memoLines,
    '',
    '## 会社が公表した数字（これ以外の数字を使わない）',
    figLines,
    peerLines ? '\n## 比較のための平均値\n' + peerLines : '',
  ].join('\n')
}
